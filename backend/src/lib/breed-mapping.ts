// Автоматическое наполнение алиасов из каталога пород РКФ
export const CANONICAL_SEARCH_TERMS = new Map<string, string[]>()
for (const b of (rkfBreedsData.breeds || [])) {
  const canon = b.canonicalRu.toUpperCase().trim()
  if (b.nameEn) {
    const en = b.nameEn.toUpperCase().trim()
    if (!BREED_ALIAS_BY_KEY[en]) BREED_ALIAS_BY_KEY[en] = canon
  }
  if (Array.isArray(b.aliases)) {
    for (const a of b.aliases) {
      const aUp = a.toUpperCase().trim()
      if (!BREED_ALIAS_BY_KEY[aUp]) BREED_ALIAS_BY_KEY[aUp] = canon
      const noHyphen = aUp.replace(/([КГДЖ])-Ш/g, '$1 Ш')
      if (!BREED_ALIAS_BY_KEY[noHyphen]) BREED_ALIAS_BY_KEY[noHyphen] = canon
      const withHyphen = aUp.replace(/([КГДЖ])\s+Ш/g, '$1-Ш')
      if (!BREED_ALIAS_BY_KEY[withHyphen]) BREED_ALIAS_BY_KEY[withHyphen] = canon
    }
  }

  // Поисковые термины: русские имена, латинские имена FCI, синонимы и аббревиатуры
  const terms = new Set<string>()
  if (b.canonicalRu) terms.add(b.canonicalRu.toLowerCase().trim())
  if (b.nameRu) terms.add(b.nameRu.toLowerCase().trim())
  if (b.nameEn) terms.add(b.nameEn.toLowerCase().trim())
  if (Array.isArray(b.aliases)) {
    for (const a of b.aliases) {
      if (a) terms.add(a.toLowerCase().trim())
    }
  }
  const existing = CANONICAL_SEARCH_TERMS.get(canon) || []
  CANONICAL_SEARCH_TERMS.set(canon, Array.from(new Set([...existing, ...terms])))
}

/** Проверяет совпадение породы с поисковым запросом (поддерживает русский, английский и аббревиатуры) */
export function matchesBreedSearch(breed: string, query: string): boolean {
  if (!query) return true
  const q = query.toLowerCase().trim()
  const bLower = breed.toLowerCase().trim()
  if (bLower.includes(q)) return true
  const canon = canonicalBreed(breed)
  if (canon) {
    if (canon.toLowerCase().includes(q)) return true
    const canonQ = canonicalBreed(q)
    if (canonQ && (canonQ === canon || matchesBreedFilter(canon, canonQ))) return true
    const terms = CANONICAL_SEARCH_TERMS.get(canon)
    if (terms) {
      for (const t of terms) {
        if (t.includes(q)) return true
      }
    }
  }
  return false
}

export function canonicalBreed(breed: string): string {
  const raw = (breed || '').trim()
  if (!raw) return raw
  if (/^\d+$/.test(raw)) return ''
  if (/^[ЬЫьы]/.test(raw) && !/^ЫЙ\s+РЕТРИВЕР/i.test(raw) && !/^(?:ЛЬ|Ь|Л)НЫЙ\s+ТОЙ/i.test(raw)) return ''

  const upper = raw.toUpperCase().trim()
  const hyphenated = upper.replace(/([КГДЖ])\s+Ш/g, '$1-Ш')
  if (OFFICIAL_BREEDS_SET.has(hyphenated)) return hyphenated

  // 1. Очистка артефактов PDF, сносок со звёздочками и склеек
  const clean = sanitizeBreedName(raw)
  if (!clean || clean === 'БЕЗ ПОРОДЫ') {
    return clean || ''
  }

  // 2. Проверка по словарю алиасов и синонимов
  const full = breedNormalizeKey(clean).replace(/\s*\/+\s*$/, '').trim()
  if (BREED_ALIAS_BY_KEY[full]) return BREED_ALIAS_BY_KEY[full]
  const key = breedAliasKey(clean).replace(/\s*\/+\s*$/, '').trim()
  if (BREED_ALIAS_BY_KEY[key]) return BREED_ALIAS_BY_KEY[key]

  // 3. Проверка по белому списку официального каталога пород
  if (OFFICIAL_BREEDS_SET.has(full)) return full
  if (OFFICIAL_BREEDS_SET.has(key)) return key
  const noHyphen = key.replace(/([КГДЖ])-Ш/g, '$1 Ш')
  if (OFFICIAL_BREEDS_SET.has(noHyphen)) return noHyphen
  const withHyphen = key.replace(/([КГДЖ])\s+Ш/g, '$1-Ш')
  if (OFFICIAL_BREEDS_SET.has(withHyphen)) return withHyphen

  // 4. Если строка не распознана как официальная порода — возвращаем пустую строку
  return ''
}

export function breedDbVariants(filterBreed: string): string[] {
  const canonical = canonicalBreed(filterBreed)
  const variants = new Set<string>([filterBreed, canonical])
  for (const [key, canon] of Object.entries(BREED_ALIAS_BY_KEY)) {
    if (canon === canonical) {
      variants.add(key)
      variants.add(key.replace(/([КГДЖ])-Ш/g, '$1 Ш'))
    }
  }
  return [...variants]
}

export function appendBreedFilter(
  query: string,
  params: unknown[],
  breed: string,
  column = 'd.breed',
): { query: string; params: unknown[] } {
  if (!breed) return { query, params }
  const variants = breedDbVariants(breed)
  const placeholders = variants.map(() => '?').join(', ')
  return {
    query: `${query} AND ${column} IN (${placeholders})`,
    params: [...params, ...variants],
  }
}

export function matchesBreedFilter(rowBreed: string | null | undefined, filterBreed: unknown): boolean {
  if (!filterBreed) return true
  if (!rowBreed) return false
  const rowRaw = String(rowBreed).trim()
  const filterRaw = String(filterBreed).trim()
  if (!rowRaw || !filterRaw) return false
  if (rowRaw.toUpperCase() === filterRaw.toUpperCase()) return true

  const canonRow = breedAliasKey(canonicalBreed(rowRaw) || rowRaw)
  const canonFilter = breedAliasKey(canonicalBreed(filterRaw) || filterRaw)
  if (canonRow === canonFilter) return true

  // Support base-breed matching for sport varieties (e.g. Podenco Ibicenco, German Shepherd, Vizsla, Xoloitzcuintli, Dachshund, Poodle)
  if (canonRow.startsWith(canonFilter + ' ') || canonFilter.startsWith(canonRow + ' ')) return true
  if (canonRow.startsWith(canonFilter + '(') || canonFilter.startsWith(canonRow + '(')) return true
  if (canonFilter.includes('ВЫЖЛА') && canonRow.includes('ВЫЖЛА')) return true
  if (canonFilter.includes('КСОЛОИТЦКУИНТЛИ') && canonRow.includes('КСОЛОИТЦКУИНТЛИ')) return true
  if (canonFilter.includes('ПИТ') && canonFilter.includes('БУЛЬ') && canonRow.includes('ПИТ') && canonRow.includes('БУЛЬ')) return true
  if (canonFilter.includes('ТАКСА') && canonRow.includes('ТАКСА')) return true
  if (canonFilter.includes('ПУДЕЛЬ') && canonRow.includes('ПУДЕЛЬ')) return true
  return false
}
