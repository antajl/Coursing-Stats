/** Нормализация без снятия RU/EN хвоста — для алиасов вроде «АКИТА / AMERICAN». */
export function breedNormalizeKey(breed: string): string {
  return breed
    .normalize('NFKC')
    .trim()
    .toUpperCase()
    .replace(/Ё/g, 'Е')
    .replace(/[\u00a0]/g, ' ')
    .replace(/\s+/g, ' ')
    // JS \b is ASCII-only — use explicit separators for К Ш → К-Ш
    .replace(/(^|[\s(,])([КГДЖ])\s+Ш(?=$|[\s),])/g, '$1$2-Ш')
    .replace(/\s*,\s*/g, ', ')
    .replace(/\s*-\s*/g, '-')
    .replace(/КОНТИНЕНТАЛЬНЫЙТОЙ/g, 'КОНТИНЕНТАЛЬНЫЙ ТОЙ')
    .replace(/\s+/g, ' ')
    .replace(/\s*[–—-]\s*$/u, '')
    .trim()
}

export function breedAliasKey(breed: string): string {
  return breedNormalizeKey(breed)
    // RKF bilingual: «САЛЮКИ / SALUKI» → «САЛЮКИ» (хвост только латиницей)
    .replace(/\s*\/\s*[A-Z][A-Z0-9\s\-'.]*$/u, '')
    .trim()
}

