for idx, d in enumerate(dogs, 1):
    cat_no = int(d["catalog_number"])
    breed = d["breed"]
    class_t = d["class"]
    gender = d["gender"]
    name_ru = d["name_ru"]
    name_lat = d["name_lat"]
    place = d["place"]
    tot = d["total_score"]
    ccl = d["ccl"] or ""
    title = d["title"] or ""
    absent = d["absent"]
    
    if absent:
        status = "absent"
        status_reason = "Неявка"
    elif any(h.get("disqualified") for h in d["heats"]):
        # Check what kind of dq
        dq_heats = [h for h in d["heats"] if h.get("disqualified")]
        r = dq_heats[-1].get("reason", "Дисквалификация")
        if "Травма" in r:
            status = "injured"
            status_reason = "Травма"
        elif "Снят" in r:
            status = "withdrawn"
            status_reason = r
        else:
            status = "disqualified"
            status_reason = r
    else:
        status = "finished"
        status_reason = None
        
    # convert heats to raw_scores_json format
    out_heats = []
    for h_in in d["heats"]:
        if h_in.get("disqualified"):
            out_heats.append({
                "heat_number": h_in.get("heat_number"),
                "bib_color": h_in.get("bib_color"),
                "disqualified": True if "Дисквалификация" in h_in.get("reason", "") else False,
                "disqualification_reason": h_in.get("reason", "")
            })
        else:
            j_list = []
            for j_idx, j_item in enumerate(h_in["judges"], 1):
                j_scores = [
                    j_item["scores"]["agility"],
                    j_item["scores"]["speed"],
                    j_item["scores"]["endurance"],
                    j_item["scores"]["follow"],
                    j_item["scores"]["enthusiasm"]
                ]
                j_list.append({
                    "judge_number": j_idx,
                    "scores": j_scores,
                    "sum": j_item["sum"]
                })
            heat_dict = {
                "heat_number": h_in.get("heat_number"),
                "bib_color": h_in.get("bib_color"),
                "judges": j_list,
                "total": h_in["total"]
            }
            if h_in.get("penalty"):
                heat_dict["penalty"] = h_in["penalty"]
                heat_dict["comment"] = h_in["comment"]
            out_heats.append(heat_dict)
            
    res_obj = {
        "id": idx,
        "catalog_no": cat_no,
        "breed_class": f"{breed} - {class_t} - {gender}",
        "placement": place,
        "total_score": tot,
        "judge_count": 2 if not absent else 0,
        "qualification": ccl,
        "vc": title,
        "status": status,
        "status_reason": status_reason,
        "dog": {
            "name_ru": name_ru,
            "name_lat": name_lat,
            "breed": breed,
            "sex": gender
        },
        "raw_scores_json": {
            "heats": out_heats,
            "grand_total": tot,
            "format": "coursing"
        }
    }
    results.append(res_obj)

