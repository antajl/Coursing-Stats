def h(num, bib, j1, j2, dq=False, snyat=False, travma=False, penalty=0, reason=""):
    if snyat:
        return {"heat_number": num, "bib_color": bib, "disqualified": True, "reason": reason or "Снят"}
    if travma:
        return {"heat_number": num, "bib_color": bib, "disqualified": True, "reason": reason or "Травма"}
    if dq:
        return {"heat_number": num, "bib_color": bib, "disqualified": True, "reason": reason or "Дисквалификация"}
    
    j1_s = sum(j1)
    j2_s = sum(j2)
    tot = j1_s + j2_s - penalty
    obj = {
        "heat_number": num,
        "bib_color": bib,
        "judges": [
            {
                "judge_name": "Кудрявцева Н.Г.",
                "scores": {"agility": j1[0], "speed": j1[1], "endurance": j1[2], "follow": j1[3], "enthusiasm": j1[4]},
                "sum": j1_s
            },
            {
                "judge_name": "Гольдинова Л.М.",
                "scores": {"agility": j2[0], "speed": j2[1], "endurance": j2[2], "follow": j2[3], "enthusiasm": j2[4]},
                "sum": j2_s
            }
        ],
        "total": tot
    }
    if penalty > 0:
        obj["penalty"] = penalty
        obj["comment"] = "Ранний старт (штраф 10% от суммы баллов забега)"
    return obj

def dog(num, breed, class_t, gender, name_ru, name_lat, h1, h2, place=None, ccl="", title="", absent=False, expected_total=None):
    if absent:
        heats = []
        tot = None
    else:
        heats = [x for x in [h1, h2] if x is not None]
        valid_totals = [x["total"] for x in heats if "total" in x]
        if len(valid_totals) == 2:
            tot = sum(valid_totals)
        elif len(valid_totals) == 1 and any(x.get("disqualified") for x in heats):
            tot = valid_totals[0]
        else:
            tot = None
            
    if expected_total is not None and tot != expected_total:
        raise ValueError(f"Dog #{num} ({name_ru or name_lat}): calculated total {tot} != expected {expected_total}")

    return {
        "catalog_number": str(num),
        "breed": breed,
        "class": class_t,
        "gender": gender,
        "name_ru": name_ru,
        "name_lat": name_lat,
        "place": place,
        "total_score": tot,
        "ccl": ccl if ccl else None,
        "title": title if title else None,
        "absent": absent,
        "heats": heats
    }

