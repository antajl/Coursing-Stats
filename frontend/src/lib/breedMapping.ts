/**
 * Синонимы пород → каноническое имя (номенклатура РКФ / FCI).
 * Склеиваем только одинаковую породу с разным написанием.
 * НЕ склеиваем: тип шерсти, размер, окрас, если в РКФ/FCI это отдельные стандарты.
 * Канон (`canonicalBreed`) — UPPERCASE ключ для фильтров/индексов.
 * Держать синхронно с backend/src/lib/breed-mapping.ts
 */

/** Нормализация без снятия RU/EN хвоста — для алиасов вроде «АКИТА / AMERICAN». */
/** Очистка артефактов парсинга PDF и опечаток в названиях пород */
export function sanitizeBreedName(raw: string): string {
  if (!raw) return ''
  let str = raw.normalize('NFKC').trim()

  // 1. Убираем сноски, звездочки и буллеты (*Порода -> Порода)
  str = str.replace(/[*•]/g, '').trim()

  if (/^\d+$/.test(str)) return ''
  if (!str || /^(?:SIGHTHOUND)?БЕЗ\s+ПОРОДЫ$/i.test(str)) {
    return 'БЕЗ ПОРОДЫ'
  }

  // 2. Мешанина из множества пород (сбой переноса строк в PDF)
  if (str.includes('ДОБЕРМАН ДОБЕРМАН ДОБЕРМАН')) {
    return 'БЕРНСКИЙ ЗЕННЕНХУНД'
  }

  // 3. Случайно приклеенная предыдущая порода в шапке (mergeBreedCarry)
  if (/^БАСЕНДЖИ\s+(?:КСОЛОИТЦКУИНТЛИ|НЕМЕЦКИЙ|ВОЛЬФШПИЦ|ЗАПАДНОСИБИРСКАЯ|КАРЕЛЬСКАЯ|ГОЛАЯ|ИНТЛИ|СОБАКА)/i.test(str)) {
    str = str.replace(/^БАСЕНДЖИ\s+/i, '')
  }
  if (/^АКИТА\s+БАСЕНДЖИ/i.test(str)) {
    return 'АКИТА'
  }
  if (/^МОПС\s+ПУДЕЛЬ/i.test(str)) {
    str = str.replace(/^МОПС\s+/i, '')
  }
  if (/^(?:ЧАРЛЬЗ|КАВАЛЕР)\s+(?:КОНТИНЕНТАЛЬНЫЙ|ЬНЫЙ)/i.test(str)) {
    return 'КОНТИНЕНТАЛЬНЫЙ ТОЙ СПАНИЕЛЬ ПАПИЙОН'
  }
  if (/^(?:СРЕДНЕАЗИАТСКАЯ|ТИБЕТСКИЙ)\s+ХОТОШО/i.test(str)) {
    return 'ХОТОШО (БУРЯТСКАЯ СОБАКА)'
  }
  if (/^(?:СРЕДНЕАЗИАТСКАЯ|ТИБЕТСКИЙ)\s+СОБАКА\)?/i.test(str)) {
    return 'СРЕДНЕАЗИАТСКАЯ ОВЧАРКА'
  }

  // 4. Инвертированные / разорванные зенненхунды
  if (/^ЗЕННЕНХУНД\s+БЕРНСКИЙ/i.test(str)) return 'БЕРНСКИЙ ЗЕННЕНХУНД'
  if (/^ЗЕННЕНХУНД\s+АНСКИЙ/i.test(str)) return 'АППЕНЦЕЛЛЕР ЗЕННЕНХУНД'
  if (/^ЗЕННЕНХУНД\s+БОЛЬШАЯ/i.test(str)) return 'БОЛЬШОЙ ШВЕЙЦАРСКИЙ ЗЕННЕНХУНД'
  if (/^ЗЕННЕНХУНД\s+БРАЗИЛЬСКИЙ/i.test(str)) return 'ФИЛА БРАЗИЛЕЙРО'
  if (/^ЗЕННЕНХУНД\s+ИТАЛЬЯНСКИЙ/i.test(str)) return 'ИТАЛЬЯНСКИЙ КАНЕ КОРСО'
  if (/^ЗЕННЕНХУНД\s+ЧЕХОСЛОВАЦКАЯ/i.test(str)) return 'ЧЕХОСЛОВАЦКИЙ ВЛЧАК'

  // 5. Обрывки Ксолоитцкуинтли
  if (/^(?:КСОЛОИТЦКУИНТЛИ|ИНТЛИ|СОБАКА\)|ГОЛАЯ\s+СОБАКА\))/i.test(str) && /МЕКСИКАНСКАЯ|ГОЛАЯ|СТАНДАРТН|МИНИАТЮРН/i.test(str)) {
    if (/МИНИАТЮРН/i.test(str)) return 'КСОЛОИТЦКУИНТЛИ МИНИАТЮРНЫЙ'
    if (/СРЕДН/i.test(str)) return 'КСОЛОИТЦКУИНТЛИ СРЕДНИЙ'
    return 'КСОЛОИТЦКУИНТЛИ СТАНДАРТНЫЙ'
  }

  // 6. Обрывки лаек
  if (/^ЗАПАДНОСИБИРСКАЯ/i.test(str)) return 'ЗАПАДНОСИБИРСКАЯ ЛАЙКА'
  if (/^КАРЕЛЬСКАЯ/i.test(str)) return 'КАРЕЛЬСКАЯ МЕДВЕЖЬЯ СОБАКА'

  // 7. Повторяющиеся цепочки такс из плотных таблиц
  if ((str.match(/ТАКСА/g) || []).length > 1) {
    const m = str.match(/ТАКСА\s+(?:СТАНДАРТНАЯ|МИНИАТЮРНАЯ|КРОЛИЧЬЯ)\s+(?:Г-Ш|Д-Ш|Ж-Ш|ГЛАДКОШЕРСТНАЯ|ДЛИННОШЕРСТНАЯ|ЖЕСТКОШЕРСТНАЯ)/i) ||
              str.match(/ТАКСА\s+(?:СТАНДАРТНАЯ|МИНИАТЮРНАЯ|КРОЛИЧЬЯ)/i) ||
              str.match(/ТАКСА\s+(?:Г-Ш|Д-Ш|Ж-Ш)/i)
    if (m) str = m[0]
  }

  // 8. Повторяющиеся цепочки шпицев
  if ((str.match(/ШПИЦ/g) || []).length > 1 && !str.includes('ЦВЕРГШПИЦ')) {
    if (/ТОЙ|ПОМЕРАНСК/i.test(str)) return 'НЕМЕЦКИЙ ШПИЦ ТОЙ (ПОМЕРАНСКИЙ)'
    if (/МАЛЫЙ/i.test(str)) return 'НЕМЕЦКИЙ ШПИЦ МАЛЫЙ'
    if (/СРЕДНИЙ/i.test(str)) return 'НЕМЕЦКИЙ ШПИЦ СРЕДНИЙ'
    if (/БОЛЬШОЙ/i.test(str)) return 'НЕМЕЦКИЙ ШПИЦ БОЛЬШОЙ'
    if (/ВОЛЬФШПИЦ|КЕЕСХОНД/i.test(str)) return 'ВОЛЬФШПИЦ (КЕЕСХОНД)'
  }

  // 9. Австралийская пастушья собака
  if (/АВСТРАЛИЙСКАЯ\s+(?:ПАСТУШЬЯ\s+)?СОБАКА\s*\(\s*АВСТРАЛИЙСКИЙ/i.test(str) ||
      /^ПАСТУШЬЯ\s+СОБАКА\s*\(\s*АВСТРАЛИЙСКИЙ/i.test(str)) {
    return 'АВСТРАЛИЙСКАЯ ПАСТУШЬЯ СОБАКА (ХИЛЕР)'
  }

  // 10. Папийон / Фален
  if (/КОНТИНЕНТАЛЬНЫЙ\s+ТОЙ\s+СПАНИЕЛЬ.*ПАПИЙОН/i.test(str)) {
    return 'КОНТИНЕНТАЛЬНЫЙ ТОЙ СПАНИЕЛЬ ПАПИЙОН'
  }

  // 11. Английский кокер спаниель
  if (/^АНГЛИЙСКИЙ\s+КОКЕР\s+СПАНИЕЛЬ/i.test(str)) {
    return 'АНГЛИЙСКИЙ КОКЕР СПАНИЕЛЬ'
  }

  // 12. Англоязычные варианты
  if (/^POODLE\s+TOY/i.test(str)) return 'ПУДЕЛЬ ТОЙ'
  if (/^POODLE\s+MINIATURE/i.test(str)) return 'ПУДЕЛЬ МИНИАТЮРНЫЙ'
  if (/^POODLE\s+STANDARD/i.test(str) || /^STANDARD\s+BLACK/i.test(str)) return 'ПУДЕЛЬ СТАНДАРТНЫЙ'
  if (/^(?:GERMAN\s+)?SPITZ\s+TOY/i.test(str)) return 'НЕМЕЦКИЙ ШПИЦ ТОЙ (ПОМЕРАНСКИЙ)'
  if (/^FRENCH\s+BULLDOG/i.test(str)) return 'ФРАНЦУЗСКИЙ БУЛЬДОГ'

  // 13. Пудели с длинными перечислениями окрасов
  if (/^ПУДЕЛЬ\s+ТОЙ/i.test(str)) return 'ПУДЕЛЬ ТОЙ'
  if (/^ПУДЕЛЬ\s+МИНИАТЮРНЫЙ/i.test(str)) return 'ПУДЕЛЬ МИНИАТЮРНЫЙ'
  if (/^ПУДЕЛЬ\s+СРЕДНИЙ/i.test(str)) return 'ПУДЕЛЬ СРЕДНИЙ'
  if (/^ПУДЕЛЬ\s+(?:СТАНДАРТНЫЙ|БОЛЬШОЙ)/i.test(str)) return 'ПУДЕЛЬ СТАНДАРТНЫЙ'

  // 14. Закрываем незакрытую скобку на конце
  const opens = (str.match(/\(/g) || []).length
  const closes = (str.match(/\)/g) || []).length
  if (opens > closes) {
    str += ')'.repeat(opens - closes)
  }

  // 15. Убираем висячие запятые, слеши и тире на конце
  str = str.replace(/[,/;\s–—-]+$/, '').trim()

  // 16. Убираем страну происхождения в скобках: (ВЕЛИКОБРИТАНИЯ), (ГЕРМАНИЯ) и т.п.
  str = str.replace(
    /\s*\((?:ВЕЛИКОБРИТАНИЯ|ГЕРМАНИЯ|США|РОССИЯ|ФРАНЦИЯ|ХОРВАТИЯ|ИРЛАНДИЯ|БЕЛЬГИЯ|АВСТРАЛИЯ|ЧЕХИЯ|МАЛЬТА|ТИБЕТ|ИТАЛИЯ|ИСПАНИЯ|ШВЕЙЦАРИЯ|КИТАЙ|ЯПОНИЯ|КАНАДА|ПОЛЬША|ВЕНГРИЯ|ШВЕЦИЯ|НОРВЕГИЯ|ФИНЛЯНДИЯ|ДАНИЯ|МЕКСИКА|ТАЙЛАНД|НИДЕРЛАНДЫ|БРАЗИЛИЯ|ЮАР|ШОТЛАНДИЯ|АНГЛИЯ)\)/gi,
    '',
  )

  // 17. Убираем служебные пометки каталогов в скобках
  str = str.replace(/\s*\((?:ОШИБКА|ИЗМЕНЕНО|ВЫСТАВЛЯЕТСЯ|ВНЕ РИНГА|РЕШЕНИЕ)[^)]*\)/gi, '')

  // 18. Окрасы и разновидности в рамках одной породы
  if (/^ФРАНЦУЗСКИЙ\s+БУЛЬДОГ.*(?:ПЯТНИСТЫЙ|ПАЛЕВЫЙ|СПЛОШНОЙ|ПЕСТРЫЙ)/i.test(str)) {
    return 'ФРАНЦУЗСКИЙ БУЛЬДОГ'
  }
  if (/^МОПС\s+(?:БЕЖЕВЫЙ|ЧЕРНЫЙ|СЕРЕБРИСТЫЙ|ПАЛЕВЫЙ|ОКРАС)/i.test(str)) {
    return 'МОПС'
  }
  if (/^ДОБЕРМАН\s+(?:ЧЕРНО-ПОДПАЛЫЙ|КОРИЧНЕВО-ПОДПАЛЫЙ|ЧЕРНЫЙ\s+С\s+ПОДПАЛОМ)/i.test(str)) {
    return 'ДОБЕРМАН'
  }
  if (/^НЕМЕЦКИЙ\s+БОКСЕР.*(?:РЫЖИЙ|ТИГРОВЫЙ)/i.test(str)) {
    return 'НЕМЕЦКИЙ БОКСЕР'
  }
  if (/^БУЛЬТЕРЬЕР\s+МИНИАТЮРНЫЙ.*(?:БЕЛЫЙ|ЦВЕТНОЙ)/i.test(str)) {
    return 'БУЛЬТЕРЬЕР МИНИАТЮРНЫЙ'
  }
  if (/^ШНАУЦЕР.*ШНАУЦЕР/i.test(str)) {
    if (/ЧЕРН/i.test(str)) return 'ШНАУЦЕР ЧЕРНЫЙ'
    return 'ШНАУЦЕР П-С'
  }
  if (/^ЦВЕРГШНАУЦЕР.*ШНАУЦЕР/i.test(str)) {
    return 'ЦВЕРГШНАУЦЕР ЧЕРНЫЙ С СЕРЕБРИСТЫМ ПОДПАЛОМ'
  }
  if (/СПРИНГЕР\s+СПАНИЕЛЬ.*ЗОЛОТИСТЫЙ\s+РЕТРИВЕР/i.test(str)) {
    return 'АНГЛИЙСКИЙ СПРИНГЕР СПАНИЕЛЬ'
  }

  return str.replace(/\s+/g, ' ').trim()
}

export function breedNormalizeKey(breed: string): string {
  return breed
    .normalize('NFKC')
    .trim()
    .toUpperCase()
    .replace(/Ё/g, 'Е')
    .replace(/[\u00a0]/g, ' ')
    .replace(/\s+/g, ' ')
    // JS \b is ASCII-only — use explicit separators for К Ш → К-Ш
    .replace(/(^|[\s(,])([КГДЖ])[\s/]+Ш(?=$|[\s),])/g, '$1$2-Ш')
    .replace(/\(([КГДЖ]-Ш)\)/g, '$1')
    .replace(/\s*,\s*/g, ', ')
    .replace(/\s*-\s*/g, '-')
    .replace(/КОНТИНЕНТАЛЬНЫЙТОЙ/g, 'КОНТИНЕНТАЛЬНЫЙ ТОЙ')
    .replace(/\s+/g, ' ')
    .replace(/\s*[–—-]\s*$/u, '')
    .trim()
}

/** Ключ для поиска алиаса: нормализация + снятие латинского хвоста « / SALUKI». */
export function breedAliasKey(breed: string): string {
  return breedNormalizeKey(breed)
    // RKF bilingual: «САЛЮКИ / SALUKI» → «САЛЮКИ» (хвост только латиницей)
    .replace(/\s*\/\s*[A-Z][A-Z0-9\s\-'.]*$/u, '')
    .trim()
}

