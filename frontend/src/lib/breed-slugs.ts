export function getCanonicalBySlug(slug: string): string | undefined {
  const norm = slug.toLowerCase().replace(/\/+$/, '').trim();
  const found = BREED_SLUG_ENTRIES.find((b) => b.slug === norm || b.aliases?.includes(norm));
  return found?.canonicalKey;
}

export function getSlugByCanonicalKey(key: string): string | undefined {
  const upper = key.toUpperCase().trim();
  const found = BREED_SLUG_ENTRIES.find(
    (b) => b.canonicalKey === upper || (upper.includes('ТАКСА') && b.canonicalKey === 'ТАКСА') || (b.aliases && b.aliases.includes(upper)),
  );
  return found?.slug;
}
