/**
 * Подсказки и расшифровка аббревиатур метаданных выставок РКФ
 * (клуб-организатор, ранг выставки, членская федерация).
 */

export interface MetaTooltipInfo {
  title: string
  description: string
}

/**
 * Расшифровка членской федерации РКФ (type).
 */
export function getFederationTooltip(rawType?: string | null): MetaTooltipInfo | null {
  if (!rawType) return null
  const norm = rawType.trim()
  if (!norm) return null
  const upper = norm.toUpperCase()

  if (upper.startsWith('РФСС')) {
    return {
      title: 'РФСС — Российская федерация служебного собаководства',
      description:
        'Общероссийская общественная организация, одна из четырёх членских федераций — учредителей РКФ (вместе с РФОС, РФЛС и ОАНКОО). Клубы состоят в РКФ через свои федерации.',
    }
  }

  if (upper.startsWith('РФОС')) {
    return {
      title: 'РФОС — Российская федерация охотничьего собаководства',
      description:
        'Общероссийская общественная организация, членская федерация РКФ. Объединяет клубы охотничьих пород, курирует выставки и полевые испытания.',
    }
  }

  if (upper.startsWith('РФЛС')) {
    return {
      title: 'РФЛС — Российская федерация любительского собаководства',
      description:
        'Союз общественных кинологических организаций, крупнейшая любительская федерация в составе РКФ.',
    }
  }

  if (upper.startsWith('ОАНКОО')) {
    let sub = ''
    if (upper.includes('РКК')) sub = ' (клубное подразделение РКК)'
    else if (upper.includes('ФАУНА')) sub = ' (клубное подразделение «Фауна»)'
    else if (upper.includes('ЭЛИТА')) sub = ' (клубное подразделение «Элита»)'
    return {
      title: `ОАНКОО — Общероссийская ассоциация независимых кинологических общественных объединений${sub}`,
      description:
        'Членская ассоциация РКФ, объединяющая независимые кинологические клубы и центры по всей России.',
    }
  }

  return {
    title: norm,
    description: 'Членская федерация / кинологическая структура в системе Российской кинологической федерации (РКФ).',
  }
}

/**
 * Расшифровка выставочного ранга (rank).
 */
export function getRankTooltip(rawRank?: string | null): MetaTooltipInfo | null {
  if (!rawRank) return null
  const norm = rawRank.trim()
  if (!norm) return null
  const upper = norm.toUpperCase()

  if (upper.includes('CACIB')) {
    return {
      title: 'CACIB FCI — Международная выставка',
      description:
        'Интернациональная сертификатная выставка высшего ранга FCI. Присуждаются международные сертификаты CACIB (Кандидат в интернациональные чемпионы красоты FCI) и национальные CAC.',
    }
  }

  if (upper.includes('ОСОБЫМ СТАТУСОМ') || upper.includes('ЧРКФ ОС')) {
    const noCac = upper.includes('БЕЗ CAC') || upper.includes('БЕЗ САС')
    return {
      title: `${norm} — Чемпион РКФ с особым статусом`,
      description:
        `Национальная выставка повышенного статуса. ${
          noCac
            ? 'Сертификаты ЧРКФ присуждаются победителям каждого взрослого класса (без присуждения CAC).'
            : 'Сертификаты CAC и Чемпион РКФ (ЧРКФ) присуждаются победителям каждого взрослого класса (промежуточный, открытый, рабочий, чемпионы), а не только лучшему кобелю и суке.'
        }`,
    }
  }

  if (upper.includes('ЧРКФ')) {
    const noCac = upper.includes('БЕЗ CAC') || upper.includes('БЕЗ САС')
    return {
      title: `${norm} — Чемпион РКФ`,
      description: noCac
        ? 'Национальная выставка ранга «Чемпион РКФ» без присуждения кандидатских сертификатов CAC.'
        : 'Национальная всепородная выставка ранга «Чемпион РКФ». Победителям сравнения взрослых классов присуждается титул «Чемпион РКФ» и сертификат CAC (Кандидат в чемпионы России).',
    }
  }

  if (upper.includes('ЧФ')) {
    const hasGroup = /(\d+)\s*ГР/i.exec(upper)
    const groupText = hasGroup ? ` для собак ${hasGroup[1]}-й группы FCI` : ''
    const noCac = upper.includes('БЕЗ CAC') || upper.includes('БЕЗ САС')
    return {
      title: `${norm} — Чемпион Федерации`,
      description:
        `Национальная сертификатная выставка ранга «Чемпион Федерации»${groupText}. Победителям присуждается сертификат ЧФ соответствующей федерации (РФСС, РФОС, РФЛС, ОАНКОО)${
          !noCac ? ' и сертификат CAC' : ''
        }. Набор из 3 сертификатов ЧФ разных федераций даёт титул Чемпиона РКФ.`,
    }
  }

  if (upper.includes('КЧК В КАЖДОМ КЛАССЕ')) {
    return {
      title: 'КЧК в каждом классе — Монопородная выставка',
      description:
        'Специализированная выставка Национального клуба породы (НКП), на которой сертификат КЧК (Кандидат в чемпионы клуба) присуждается победителю каждого взрослого класса.',
    }
  }

  if (upper.includes('КЧК')) {
    return {
      title: 'КЧК — Кандидат в чемпионы клуба',
      description:
        'Монопородная выставка Национального клуба породы (НКП) с присуждением сертификата КЧК лучшему кобелю и лучшей суке породы.',
    }
  }

  if (upper.includes('ПК') || upper.includes('ПОБЕДИТЕЛЬ КЛУБА')) {
    return {
      title: 'ПК — Победитель клуба года',
      description:
        'Главная ежегодная монопородная выставка Национального клуба породы. Победители получают титул «Победитель клуба года» (ПК) или «Чемпион клуба года».',
    }
  }

  if (upper.includes('ПП')) {
    return {
      title: 'ПП — Победитель породы',
      description:
        'Монопородная выставка ранга «Победитель породы» с присуждением сертификатов Национального клуба породы (НКП).',
    }
  }

  const groupMatch = /(?:CAC|САС)\s*(\d+)\s*ГР/i.exec(upper)
  if (groupMatch) {
    return {
      title: `${norm} — Выставка группы пород FCI`,
      description: `Сертификатная выставка ранга CAC для собак ${groupMatch[1]}-й группы пород FCI с присуждением сертификатов CAC (Кандидат в чемпионы России).`,
    }
  }

  if (upper.includes('CAC') || upper.includes('САС')) {
    return {
      title: `${norm} — Сертификатная выставка CAC`,
      description:
        'Национальная всепородная выставка с присуждением сертификата CAC (Certificat d\'Aptitude au Championnat — Кандидат в чемпионы России по красоте).',
    }
  }

  return {
    title: norm,
    description: 'Официальный выставочный ранг мероприятия в системе Российской кинологической федерации (РКФ).',
  }
}

/**
 * Расшифровка аббревиатур в названии клуба-организатора (club).
 */
export function getClubTooltip(rawClub?: string | null): MetaTooltipInfo | null {
  if (!rawClub) return null
  const norm = rawClub.trim()
  if (!norm) return null

  const parts: string[] = []
  const hasWord = (w: string) => new RegExp(`(^|[^а-яёА-ЯЁa-zA-Z0-9])${w}([^а-яёА-ЯЁa-zA-Z0-9]|$)`, 'i').test(norm)

  if (hasWord('РОО')) parts.push('РОО — Региональная общественная организация')
  if (hasWord('МОО')) parts.push('МОО — Межрегиональная общественная организация')
  if (hasWord('МКОО')) parts.push('МКОО — Межрегиональная кинологическая общественная организация')
  if (hasWord('РОКО')) parts.push('РОКО — Региональная общественная кинологическая организация')
  if (hasWord('ОО') && !parts.some((p) => p.includes('общественная организация'))) {
    parts.push('ОО — Общественная организация')
  }
  if (hasWord('КЛЖ')) parts.push('КЛЖ — Клуб любителей животных')
  if (hasWord('КК')) parts.push('КК — Кинологический клуб')
  if (hasWord('ККС')) parts.push('ККС — Клуб кинологического собаководства / спорта')
  if (hasWord('КПЦ')) parts.push('КПЦ — Кинологический племенной центр')
  if (hasWord('ЦСПС')) parts.push('ЦСПС — Центр спортивного и прикладного собаководства')
  if (hasWord('СОКК')) parts.push('СОКК — Саратовский областной кинологический клуб')
  if (hasWord('ДРПЦС')) parts.push('ДРПЦС — Донецкий региональный племенной центр собаководства')

  const desc =
    parts.length > 0
      ? `${parts.join('; ')}. Кинологический клуб-организатор выставки в системе РКФ.`
      : 'Кинологический клуб-организатор, аккредитованный в Российской кинологической федерации (РКФ) для проведения официальных выставок.'

  return {
    title: norm,
    description: desc,
  }
}
